-- GaleFusionCompat - writes the mods.yml file NynrahGhost-Fusion expects.
--
-- Fusion.exe reads "<profile>\mods.yml" (the mod list r2modman keeps) while
-- building FusionPatch_P. Gale does not keep that file, so Fusion throws
-- FileNotFoundException and the game closes on launch. This mod generates the
-- file from the profile's installed packages every time the game starts.
--
-- It never touches a mods.yml that r2modman wrote: outside Gale it only creates
-- the file when it is missing, or refreshes one it created itself.
--
-- See https://github.com/Kesomannen/gale/issues/740

local PREFIX = "[GaleFusionCompat] "
local MARKER = "# generated by GaleFusionCompat"

local function log(message)
    print(PREFIX .. tostring(message) .. "\n")
end

local function readFile(path)
    local file = io.open(path, "rb")
    if not file then
        return nil
    end
    local content = file:read("*all")
    file:close()
    return content
end

local function exists(path)
    local file = io.open(path, "rb")
    if file then
        file:close()
        return true
    end
    return false
end

-- Folder holding the game exe, taken from this script's own path:
-- "...\Binaries\Win64\Mods\<this mod>\Scripts\main.lua"
local function getExeDir()
    local src = debug.getinfo(1, "S").source:gsub("^@", "")
    local lower = src:lower()
    local index = nil
    local from = 1
    while true do
        local found = lower:find("\\mods\\", from, true)
        if not found then
            break
        end
        index = found
        from = found + 1
    end
    if not index then
        return nil
    end
    return src:sub(1, index - 1)
end

-- shimloader logs the arguments it was started with, including --mod-dir.
local function getModDir(exeDir)
    local shimLog = readFile(exeDir .. "\\shimloader-log.txt")
    if not shimLog then
        return nil
    end
    -- args: [..., "--mod-dir", "C:\\Users\\...\\shimloader\\mod", ...]
    local path = shimLog:match('"%-%-mod%-dir",%s*"(.-)"')
    if not path then
        return nil
    end
    return (path:gsub("\\\\", "\\"))
end

local function listFolders(path)
    local folders = {}
    local pipe = io.popen('dir /b /ad "' .. path .. '" 2>nul')
    if not pipe then
        return folders
    end
    for line in pipe:lines() do
        line = line:gsub("[\r\n]+$", "")
        if line ~= "" then
            folders[#folders + 1] = line
        end
    end
    pipe:close()
    table.sort(folders, function(a, b) return a:lower() < b:lower() end)
    return folders
end

local function quote(value)
    return '"' .. tostring(value):gsub("\\", "\\\\"):gsub('"', '\\"'):gsub("[\r\n]+", " ") .. '"'
end

local function buildModsYml(modDir)
    local lines = { MARKER }
    local count = 0

    for _, folder in ipairs(listFolders(modDir)) do
        local author, name = folder:match("^([^%-]+)%-(.+)$")
        local manifestPath = modDir .. "\\" .. folder .. "\\manifest.json"
        -- Gale disables a package by renaming its files to *.old
        local enabled = exists(manifestPath)
        if not enabled and exists(manifestPath .. ".old") then
            manifestPath = manifestPath .. ".old"
        end
        local manifest = author and readFile(manifestPath)

        if manifest then
            local version = manifest:match('"version_number"%s*:%s*"([^"]*)"') or "0.0.0"
            local description = manifest:match('"description"%s*:%s*"([^"]*)"') or ""
            local major, minor, patch = version:match("^(%d+)%.?(%d*)%.?(%d*)")

            lines[#lines + 1] = "- manifestVersion: 1"
            lines[#lines + 1] = "  name: " .. quote(folder)
            lines[#lines + 1] = "  authorName: " .. quote(author)
            lines[#lines + 1] = "  websiteUrl: " .. quote("https://thunderstore.io/c/voices-of-the-void/p/" .. author .. "/" .. name .. "/")
            lines[#lines + 1] = "  displayName: " .. quote(name)
            lines[#lines + 1] = "  description: " .. quote(description)
            lines[#lines + 1] = '  gameVersion: "0"'
            lines[#lines + 1] = "  networkMode: both"
            lines[#lines + 1] = "  packageType: other"
            lines[#lines + 1] = "  installMode: managed"
            lines[#lines + 1] = "  loaders: []"
            lines[#lines + 1] = "  dependencies: []"
            lines[#lines + 1] = "  incompatibilities: []"
            lines[#lines + 1] = "  optionalDependencies: []"
            lines[#lines + 1] = "  versionNumber:"
            lines[#lines + 1] = "    major: " .. (tonumber(major) or 0)
            lines[#lines + 1] = "    minor: " .. (tonumber(minor) or 0)
            lines[#lines + 1] = "    patch: " .. (tonumber(patch) or 0)
            lines[#lines + 1] = "  enabled: " .. tostring(enabled)
            count = count + 1
        end
    end

    if count == 0 then
        lines[#lines + 1] = "[]"
    end
    return table.concat(lines, "\n") .. "\n", count
end

local function run()
    local exeDir = getExeDir()
    if not exeDir then
        log("Could not work out the game folder from the script path; doing nothing.")
        return
    end

    local modDir = getModDir(exeDir)
    if not modDir then
        log("No --mod-dir in shimloader-log.txt; not launched by a mod manager, doing nothing.")
        return
    end

    local profileDir = modDir:match("^(.*)\\shimloader\\mod\\?$")
    if not profileDir then
        log("Mod folder is not inside a <profile>\\shimloader\\mod layout: " .. modDir)
        return
    end

    local ymlPath = profileDir .. "\\mods.yml"
    local current = readFile(ymlPath)
    local isGale = profileDir:lower():find("com.kesomannen.gale", 1, true) ~= nil
    local ours = current ~= nil and current:sub(1, #MARKER) == MARKER

    if current and not isGale and not ours then
        log("mods.yml already exists and was written by the mod manager; leaving it alone.")
        return
    end

    local content, count = buildModsYml(modDir)
    if content == current then
        log("mods.yml is up to date (" .. count .. " packages).")
        return
    end

    local file = io.open(ymlPath, "wb")
    if not file then
        log("Could not write " .. ymlPath)
        return
    end
    file:write(content)
    file:close()
    log("Wrote " .. ymlPath .. " (" .. count .. " packages).")
end

local ok, err = pcall(run)
if not ok then
    log("Error: " .. tostring(err))
end
